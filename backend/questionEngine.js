class QuestionEngine {
    static getNextMove(context) {
        if (context.isReadyForMatching) {
            return "PROCESSING_RECOMMENDATION";
        }

        if (context.maxQuestionsReached) {
            return "LLM_FALLBACK";
        }

        const lang = context.language || "en";
        const templates = QUESTIONS[lang] || QUESTIONS["en"];

        if (!context.intent || context.intent === "UNKNOWN") {
            context.questionCount++;
            context.lastAskedField = "intent";
            return templates["intent"];
        }

        const candidates = context.missingCriticalFields.filter(f => f !== context.lastAskedField);
        const targetField = candidates.length > 0 ? candidates[0] : context.missingCriticalFields[0];

        if (!targetField) {
            return "PROCESSING_RECOMMENDATION";
        }

        const acks = ACKS[lang] || ACKS["en"];
        const ack = acks[context.questionCount % acks.length];
        const question = templates[targetField] || (templates["fallback"] + targetField);

        context.lastAskedField = targetField;
        context.questionCount++;

        return `${ack}${question}`;
    }

    static getSchemeGuidance(context) {
        const lang = context.language || "en";
        const labels = LABELS[lang] || LABELS["en"];
        const intent = context.intent;

        const lines = [];

        const helpline = HELPLINES[intent];
        if (helpline) {
            const name = helpline.name[lang] || helpline.name["en"];
            lines.push(`📞 ${labels.helpline}: ${name} — ${helpline.number}`);
            lines.push(`   (${labels.hours}: ${helpline.hours})`);
        } else {
            lines.push(`📞 ${labels.helpline}: ${GENERAL_HELP[lang] || GENERAL_HELP["en"]}`);
        }

        const steps = STEPS[intent]?.[lang] || STEPS[intent]?.["en"];
        if (steps) {
            lines.push("");
            lines.push(`${labels.steps}:`);
            steps.forEach((step, i) => {
                lines.push(`${i + 1}. ${step}`);
            });
        }

        return lines.join("\n");
    }
}

module.exports = { QuestionEngine };
